/* Immersive Story Engine v1.0 — Stage 4 export compilers */
window.ISE_EXPORT = (function () {
  const ASPECT = { "2.39:1": [2048, 858], "16:9": [1920, 1080], "9:16": [1080, 1920], "1:1": [1080, 1080], "4:3": [1440, 1080] };
  const dims = (ar) => ASPECT[ar] || ASPECT["16:9"];
  const slug = (s) => (s || "project").toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");
  const pad = (n) => String(n).padStart(3, "0");
  const shq = (s) => "'" + String(s || "").replace(/'/g, "'\\''") + "'";
  const db2lin = (db) => Math.pow(10, db / 20).toFixed(4);

  function frameExport(f) {
    return {
      frame_id: f.frame_id, time_window: f.time_window,
      start_time_sec: f.start_time_sec, end_time_sec: f.end_time_sec, duration_sec: f.duration_sec,
      character_speaker: f.character_speaker || null,
      narration_text: f.narration_text || "", word_count: f.word_count, est_speech_sec: f.est_speech_sec,
      sfx_cue: f.sfx_cue || "", bgm_mood: f.bgm_mood || "",
      ducking: { gain_db: f.ducking_db, state: f.ducking },
      visual_prompt: f.visual_prompt,
      visual_components: { subject_action: f.visual_subject || "", lens_override: f.lens_override || null, lighting_atmosphere: f.lighting || "" },
      transition_in: f.transition_in, transition_out: f.transition_out,
    };
  }

  function manifest(p) {
    return JSON.stringify({
      engine: "Immersive Story Engine", version: "1.0", exported_at: new Date().toISOString(),
      project: { name: p.name, mode: p.mode, target_duration_sec: +p.target_duration, total_duration_sec: p.total_duration_sec, frame_count: p.frames.length },
      continuity_bible: { ...p.bible, resolution: dims(p.bible.aspect_ratio).join("x"), motifs: (p.bible.motifs || "").split(",").map((s) => s.trim()).filter(Boolean), negative_prompts: (p.bible.negative_prompts || "").split(",").map((s) => s.trim()).filter(Boolean) },
      voice_profiles: p.voice_profiles,
      audio_automation: { dialogue_duck_db: ISE.DUCK_DB, envelope: ISE.duckEnvelope(p) },
      frames: p.frames.map(frameExport),
    }, null, 2);
  }

  /** FFmpeg: concat per-frame clips, pad to aspect, mix dialogue + sfx + bgm with -12dB dialogue ducking. */
  function ffmpeg(p) {
    const [W, H] = dims(p.bible.aspect_ratio);
    const fps = +p.bible.fps || 24;
    const name = slug(p.bible.project_title || p.name);
    const total = p.total_duration_sec.toFixed(1);
    const L = [];
    L.push("#!/usr/bin/env bash");
    L.push(`# render_pipeline.sh — generated by Immersive Story Engine v1.0`);
    L.push(`# Project: ${p.bible.project_title}  |  ${p.name}`);
    L.push(`# Continuity Lock: ${p.bible.aspect_ratio} @ ${W}x${H}, ${fps}fps, ${p.bible.color_pipeline}, ${p.bible.camera_rig}`);
    L.push(`# Frames: ${p.frames.length}  |  Total: ${total}s  |  Dialogue ducking: ${ISE.DUCK_DB}dB (sidechaincompress) `);
    L.push("set -euo pipefail");
    L.push("");
    L.push("# ── Expected inputs (place next to this script) ─────────────────────────────");
    L.push("#   clips/frame_NNN.mp4   generated visual for each frame (any size; padded below)");
    L.push("#   vo/frame_NNN.wav      TTS/VO rendered with the voice_seed_id of character_speaker (silent frames may be missing)");
    L.push("#   sfx/frame_NNN.wav     optional sound-effect stem per frame");
    L.push("#   bgm.wav               background music bed (will be ducked under dialogue)");
    L.push(`OUT="${name}_final.mp4"`);
    L.push(`W=${W}; H=${H}; FPS=${fps}; TOTAL=${total}`);
    L.push(`DUCK_DB=${ISE.DUCK_DB}; DUCK_LIN=${db2lin(ISE.DUCK_DB)}`);
    L.push("mkdir -p build");
    L.push("");
    L.push("# ── 1) Conform each visual clip: exact duration, aspect-ratio pad, fps, pixel format ─────");
    L.push("# Transition hint per frame is left as a comment; xfade can be layered later in stage 5.");
    p.frames.forEach((f) => {
      const id = pad(f.frame_id);
      L.push(`# frame ${id}  ${f.time_window}  in:${f.transition_in} out:${f.transition_out}  ${f.character_speaker || "—"}: ${(f.narration_text || "(silent)").replace(/\n/g, " ").slice(0, 80)}`);
      L.push(`ffmpeg -y -loglevel error -i clips/frame_${id}.mp4 -t ${f.duration_sec} \\`);
      L.push(`  -vf "scale=\${W}:\${H}:force_original_aspect_ratio=decrease,pad=\${W}:\${H}:(ow-iw)/2:(oh-ih)/2:color=black,fps=\${FPS},format=yuv420p,setsar=1" \\`);
      L.push(`  -an -c:v libx264 -preset medium -crf 16 build/v_${id}.mp4`);
    });
    L.push("");
    L.push("# ── 2) Concatenate the conformed visual clips ───────────────────────────────");
    L.push("printf '' > build/concat.txt");
    L.push(`for i in $(seq -f "%03g" 1 ${p.frames.length}); do echo "file 'v_$i.mp4'" >> build/concat.txt; done`);
    L.push(`ffmpeg -y -loglevel error -f concat -safe 0 -i build/concat.txt -c copy build/video_track.mp4`);
    L.push("");
    L.push("# ── 3) Dialogue track: place each VO stem at its start_time_sec (adelay), silence where missing ─");
    const voInputs = [], voLabels = [];
    p.frames.forEach((f) => {
      if (!f.narration_text || !f.narration_text.trim()) return;
      const id = pad(f.frame_id);
      voInputs.push(`-i vo/frame_${id}.wav`);
      voLabels.push({ idx: voInputs.length - 1, id, ms: Math.round(f.start_time_sec * 1000), speaker: f.character_speaker });
    });
    if (voLabels.length) {
      L.push(`ffmpeg -y -loglevel error ${voInputs.join(" ")} \\`);
      L.push("  -filter_complex \"\\");
      voLabels.forEach((v) => L.push(`    [${v.idx}:a]aformat=sample_rates=48000:channel_layouts=stereo,adelay=${v.ms}|${v.ms}[d${v.id}]; \\   # ${v.speaker}`));
      L.push(`    ${voLabels.map((v) => `[d${v.id}]`).join("")}amix=inputs=${voLabels.length}:normalize=0:dropout_transition=0,apad=whole_dur=\${TOTAL}[dialogue]" \\`);
      L.push("  -map \"[dialogue]\" -c:a pcm_s16le build/dialogue.wav");
    } else {
      L.push("ffmpeg -y -loglevel error -f lavfi -i anullsrc=r=48000:cl=stereo -t ${TOTAL} build/dialogue.wav  # no dialogue in this cut");
    }
    L.push("");
    L.push("# ── 4) SFX track (optional stems, same placement logic) ─────────────────────");
    const sfxInputs = [], sfxLabels = [];
    p.frames.forEach((f) => { if (!f.sfx_cue) return; const id = pad(f.frame_id); sfxInputs.push(`-i sfx/frame_${id}.wav`); sfxLabels.push({ idx: sfxInputs.length - 1, id, ms: Math.round(f.start_time_sec * 1000), cue: f.sfx_cue }); });
    if (sfxLabels.length) {
      L.push("# If a stem is missing, generate silence first: ffmpeg -f lavfi -i anullsrc -t 1 sfx/frame_NNN.wav");
      L.push(`ffmpeg -y -loglevel error ${sfxInputs.join(" ")} \\`);
      L.push("  -filter_complex \"\\");
      sfxLabels.forEach((v) => L.push(`    [${v.idx}:a]aformat=sample_rates=48000:channel_layouts=stereo,adelay=${v.ms}|${v.ms}[s${v.id}]; \\   # ${v.cue.slice(0, 60)}`));
      L.push(`    ${sfxLabels.map((v) => `[s${v.id}]`).join("")}amix=inputs=${sfxLabels.length}:normalize=0:dropout_transition=0,apad=whole_dur=\${TOTAL}[sfx]" \\`);
      L.push("  -map \"[sfx]\" -c:a pcm_s16le build/sfx.wav");
    } else {
      L.push("ffmpeg -y -loglevel error -f lavfi -i anullsrc=r=48000:cl=stereo -t ${TOTAL} build/sfx.wav  # no sfx cues");
    }
    L.push("");
    L.push("# ── 5) BGM ducking: two equivalent methods. Method A is default. ────────────");
    L.push("# Method A — sidechaincompress: dialogue drives a compressor on BGM, yielding ~-12dB under speech.");
    L.push("#   threshold 0.02 (~-34dBFS), ratio 8 → ~12dB gain reduction at nominal VO level, 20ms attack / 400ms release.");
    L.push("ffmpeg -y -loglevel error -i bgm.wav -i build/dialogue.wav \\");
    L.push("  -filter_complex \"[0:a]aformat=sample_rates=48000:channel_layouts=stereo,atrim=0:${TOTAL},apad=whole_dur=${TOTAL}[bgm]; \\");
    L.push("                   [bgm][1:a]sidechaincompress=threshold=0.02:ratio=8:attack=20:release=400:makeup=1[bgm_ducked]\" \\");
    L.push("  -map \"[bgm_ducked]\" -c:a pcm_s16le build/bgm_ducked.wav");
    L.push("");
    L.push("# Method B — deterministic volume keyframes from the Beat-Split envelope (exact -12dB per frame window):");
    const expr = p.frames.filter((f) => f.ducking_db !== 0).map((f) => `between(t,${f.start_time_sec},${f.end_time_sec})`).join("+");
    L.push(`#   ffmpeg -y -i bgm.wav -af "volume='if(gt(${expr || "0"},0),\${DUCK_LIN},1)':eval=frame" build/bgm_ducked.wav`);
    L.push("#   envelope: " + ISE.duckEnvelope(p).map((e) => `[${e.t0}-${e.t1}s ${e.gain_db}dB]`).join(" "));
    L.push("");
    L.push("# ── 6) Final mix: dialogue 0dB, sfx -6dB, ducked bgm -8dB bed → loudnorm to -14 LUFS ───────");
    L.push("ffmpeg -y -loglevel error -i build/dialogue.wav -i build/sfx.wav -i build/bgm_ducked.wav \\");
    L.push("  -filter_complex \"[0:a]volume=0dB[d];[1:a]volume=-6dB[s];[2:a]volume=-8dB[b]; \\");
    L.push("                   [d][s][b]amix=inputs=3:normalize=0:duration=longest,loudnorm=I=-14:TP=-1.5:LRA=11[mix]\" \\");
    L.push("  -map \"[mix]\" -c:a pcm_s24le build/mix.wav");
    L.push("");
    L.push("# ── 7) Mux video + mix ─────────────────────────────────────────────────────");
    L.push("ffmpeg -y -loglevel error -i build/video_track.mp4 -i build/mix.wav \\");
    L.push(`  -map 0:v -map 1:a -c:v copy -c:a aac -b:a 320k -shortest -movflags +faststart \\`);
    L.push(`  -metadata title=${shq(p.bible.project_title)} -metadata comment=${shq(`ISE v1.0 | ${p.bible.color_pipeline} | ${p.bible.film_stock}`)} "$OUT"`);
    L.push("");
    L.push("# ── 8) Optional: burn-in subtitles from timeline (SRT written below) ────────");
    L.push("cat > build/subs.srt <<'SRT'");
    let n = 0;
    p.frames.forEach((f) => { if (!f.narration_text) return; n++; L.push(String(n)); L.push(`${srt(f.start_time_sec)} --> ${srt(f.end_time_sec)}`); L.push(`${f.character_speaker ? `[${f.character_speaker}] ` : ""}${f.narration_text}`); L.push(""); });
    L.push("SRT");
    L.push(`# ffmpeg -i "$OUT" -vf "subtitles=build/subs.srt" "${name}_subbed.mp4"`);
    L.push(`echo "✔ Rendered $OUT (${total}s, ${W}x${H}@${fps}fps)"`);
    return L.join("\n");
  }
  function srt(sec) { const h = Math.floor(sec / 3600), m = Math.floor((sec % 3600) / 60), s = Math.floor(sec % 60), ms = Math.round((sec - Math.floor(sec)) * 1000); return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")},${String(ms).padStart(3, "0")}`; }

  /** Remotion: props for a <Composition> — fps-exact frame offsets + sequences + audio ducking volume curve. */
  function remotion(p) {
    const [W, H] = dims(p.bible.aspect_ratio);
    const fps = +p.bible.fps || 24;
    const toF = (s) => Math.round(s * fps);
    const name = slug(p.bible.project_title || p.name);
    const sequences = p.frames.map((f) => ({
      id: `frame_${pad(f.frame_id)}`, frame_id: f.frame_id,
      from: toF(f.start_time_sec), durationInFrames: Math.max(1, toF(f.duration_sec)),
      video: { src: `clips/frame_${pad(f.frame_id)}.mp4`, prompt: f.visual_prompt, transitionIn: f.transition_in, transitionOut: f.transition_out, transitionFrames: f.transition_in === "cut" ? 0 : Math.round(fps * 0.5) },
      dialogue: f.narration_text ? { src: `vo/frame_${pad(f.frame_id)}.wav`, speaker: f.character_speaker, voice_seed_id: (p.voice_profiles[f.character_speaker] || {}).voice_seed_id || null, text: f.narration_text, subtitle: true } : null,
      sfx: f.sfx_cue ? { src: `sfx/frame_${pad(f.frame_id)}.wav`, cue: f.sfx_cue, volumeDb: -6 } : null,
      bgm: { mood: f.bgm_mood, duckDb: f.ducking_db },
    }));
    const volumeCurve = p.frames.map((f) => ({ frame: toF(f.start_time_sec), volume: +Math.pow(10, f.ducking_db / 20).toFixed(3) }));
    return JSON.stringify({
      compositionId: `ISE_${name}`,
      component: "BeatSplitTimeline",
      width: W, height: H, fps, durationInFrames: Math.max(1, toF(p.total_duration_sec)),
      defaultProps: {
        title: p.bible.project_title,
        continuity: { colorPipeline: p.bible.color_pipeline, aspectRatio: p.bible.aspect_ratio, cameraRig: p.bible.camera_rig, filmStock: p.bible.film_stock, motifs: (p.bible.motifs || "").split(",").map((s) => s.trim()).filter(Boolean), negativePrompts: p.bible.negative_prompts },
        voiceProfiles: p.voice_profiles,
        bgm: { src: "bgm.wav", baseVolumeDb: -8, duckDb: ISE.DUCK_DB, interpolate: "linear", rampFrames: Math.round(fps * 0.25), volumeCurve },
        sequences,
      },
    }, null, 2);
  }

  function highlight(code, kind) {
    const esc = code.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
    if (kind === "json") {
      return esc.replace(/("(?:\\.|[^"\\])*")(\s*:)?|\b(true|false|null)\b|(-?\d+(?:\.\d+)?(?:e[+-]?\d+)?)/g, (m, str, colon, bool, num) => {
        if (str) return colon ? `<span class="k">${str}</span>${colon}` : `<span class="s">${str}</span>`;
        if (bool) return `<span class="b">${bool}</span>`;
        return `<span class="n">${num}</span>`;
      });
    }
    return esc.split("\n").map((line) => {
      if (/^\s*#/.test(line)) return `<span class="c">${line}</span>`;
      return line
        .replace(/(#[^"']*)$/, '<span class="c">$1</span>')
        .replace(/\b(ffmpeg|set|mkdir|printf|echo|for|do|done|seq|cat)\b/g, '<span class="f">$1</span>')
        .replace(/(\$\{?[A-Z_]+\}?)/g, '<span class="v">$1</span>')
        .replace(/(\s)(-[a-z:_]+)(?=\s)/g, '$1<span class="k">$2</span>')
        .replace(/("(?:[^"\\]|\\.)*")/g, '<span class="s">$1</span>');
    }).join("\n");
  }

  return { manifest, ffmpeg, remotion, highlight, slug, dims };
})();
